import { assertBw26RepoRoot } from './io';
import { loadCanonicalState } from './state';
const root=process.cwd(); await assertBw26RepoRoot(root); const s=await loadCanonicalState(root);
const finals=s.appearances.filter((x:any)=>x.series==='BW'); const cand=s.appearances.filter((x:any)=>x.series==='BW-CAND');
const c=new Map<string,number>(); for(const x of s.candidateSelection as any[]){c.set(x.outcome,(c.get(x.outcome)??0)+1);}
const selections=s.contentSelections as any[];
const selectedStatements=selections.filter((x:any)=>x.statement?.status!=='unavailable').length;
const unavailableStatements=selections.filter((x:any)=>x.statement?.status==='unavailable').length;
const verifiedSolutions=selections.filter((x:any)=>x.solutions.status==='verified').length;
const unavailableSolutions=selections.filter((x:any)=>x.solutions.status==='unavailable').length;
const unresolvedSolutions=selections.filter((x:any)=>x.solutions.status==='unresolved').length;
const selectedSolutionFiles=selections.reduce((sum:number,x:any)=>sum+x.solutions.items.length,0);
const reviewedSubtopics=(s.classifications as any[]).filter((x:any)=>Array.isArray(x.subtopics)&&x.subtopics.length>0).length;
const statementAssetBindings=(s.assetBindings as any[]).filter((x:any)=>x.owner?.kind==='statement').length;
const solutionAssetBindings=(s.assetBindings as any[]).filter((x:any)=>x.owner?.kind==='solution').length;
const publicationComplete=selections.length===786 && selectedStatements+unavailableStatements===786 && verifiedSolutions+unavailableSolutions===786 && unresolvedSolutions===0 && (s.classifications as any[]).length===786 && reviewedSubtopics===786;
console.log('BW26 corpus report'); console.log('------------------');
console.log(`Final appearances:          ${finals.length}`); console.log('Final Versions:             719');
console.log(`Candidate sets:             ${s.candidateSets.length}`); console.log(`Candidate appearances:      ${cand.length}`);
console.log(`Total Versions:             ${s.versions.length}`); console.log(`Revision relations:         ${s.versionRelations.length}`);
console.log(`Selected candidates:        ${c.get('selected')??0}`); console.log(`Not-selected candidates:    ${c.get('not-selected')??0}`); console.log(`Selection unresolved:       ${c.get('unresolved')??0}`);
console.log(`Public shortlist-only:      ${s.publicShortlistOnly.length}`); console.log(`Canonical source links:     ${s.sourceLinks.length}`); console.log('Historical completeness:    NOT CLAIMED');
console.log(''); console.log('P3D publication layer'); console.log('---------------------');
console.log('Public Versions:             786');
console.log(`Selected statements:         ${selectedStatements}`);
console.log(`Statements unavailable:      ${unavailableStatements}`);
console.log(`Statement unresolved:        ${786-selectedStatements-unavailableStatements}`);
console.log(`Verified local solutions:    ${verifiedSolutions}`);
console.log(`Solutions unavailable:       ${unavailableSolutions}`);
console.log(`Solution unresolved:         ${unresolvedSolutions}`);
console.log(`Selected solution files:     ${selectedSolutionFiles}`);
console.log(`Asset bindings:              ${(s.assetBindings as any[]).length}`);
console.log(`Statement asset bindings:    ${statementAssetBindings}`);
console.log(`Solution asset bindings:     ${solutionAssetBindings}`);
console.log(`Primary classifications:     ${(s.classifications as any[]).length}`);
console.log(`Subtopic-reviewed Versions:  ${reviewedSubtopics}`);
console.log(`Publication completeness:    ${publicationComplete?'COMPLETE (all public content states resolved)':'INCOMPLETE'}`);
