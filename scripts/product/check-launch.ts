import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { seasonEvents, type SeasonEvent } from '../../src/data/events';
import { materialCategories } from '../../src/data/materials';
import { countdownParts, daysUntil, eventDay, eventState, nextEvent, eventDateLabel } from '../../src/lib/events';

const bw = seasonEvents.find((event) => event.id === 'baltic-way')!;
const at = (date: string) => new Date(date);
assert.equal(eventState(bw, at('2026-11-11T21:59:59Z')), 'upcoming');
assert.equal(eventState(bw, at('2026-11-11T22:00:00Z')), 'current');
assert.equal(eventState(bw, at('2026-11-16T21:59:59Z')), 'current');
assert.equal(eventState(bw, at('2026-11-16T22:00:00Z')), 'past');
assert.equal(nextEvent(seasonEvents, at('2026-10-08T12:00:00Z'))?.id, 'baltic-way');
assert.equal(nextEvent(seasonEvents, at('2026-11-17T12:00:00Z')), undefined);
assert.equal(eventState(seasonEvents[0]!, at('2026-09-26T12:00:00Z')), 'current');
assert.equal(eventState(seasonEvents[0]!, at('2026-09-26T21:00:00Z')), 'past');
assert.equal(eventState(seasonEvents[1]!, at('2026-12-01T12:00:00Z')), 'pending');
assert.equal(daysUntil(bw, at('2026-10-08T12:00:00Z')), 35);
assert.equal(daysUntil(bw, at('2026-10-24T21:00:00Z')), 18);
assert.equal(daysUntil(bw, at('2026-10-25T21:59:59Z')), 18);
assert.equal(daysUntil(bw, at('2026-10-25T22:00:00Z')), 17);
assert.equal(eventDay(at('2026-10-08T21:30:00Z'), 'Europe/Tallinn'), '2026-10-09');
assert.equal(daysUntil(bw, at('2026-11-30T12:00:00Z')), 0);
assert.equal(daysUntil(seasonEvents[1]!), null);
const timed: SeasonEvent = { ...bw, startAt: '2026-11-12T10:00:00+02:00' };
assert.equal(eventState(timed, at('2026-11-12T07:59:59Z')), 'upcoming');
assert.deepEqual(countdownParts(timed.startAt!, at('2026-11-11T06:57:56Z')), [1, 1, 2, 4]);
assert.deepEqual(countdownParts(timed.startAt!, at('2026-11-12T08:00:01Z')), [0, 0, 0, 0]);
assert.equal(eventState(timed, at('2026-11-12T08:00:00Z')), 'current');
const camp: SeasonEvent = { ...seasonEvents[1]!, startDate: '2026-10-24' };
assert.equal(nextEvent([...seasonEvents, camp], at('2026-10-08T12:00:00Z'))?.id, 'camp-1');
assert.equal(nextEvent([...seasonEvents, camp], at('2026-10-25T12:00:00Z'))?.id, 'baltic-way');
assert.equal(eventDateLabel(seasonEvents[1]!, 'et'), 'Kuupäev selgumisel');
assert.match(eventDateLabel(bw, 'et'), /november/);
assert.equal(seasonEvents.length, 5);
assert.equal(new Set(seasonEvents.map((event) => event.id)).size, 5);
for (const event of seasonEvents) {
  assert.ok(event.title.en && event.title.et);
  if (event.startAt) assert.match(event.startAt, /(?:Z|[+-]\d{2}:\d{2})$/);
  if (event.startDate && event.endDate) assert.ok(event.endDate >= event.startDate);
}
assert.equal(materialCategories.length, 5);
const links = materialCategories.flatMap((category) => [...category.links]);
assert.equal(links.length, 13);
assert.equal(new Set(links.map((link) => link.url)).size, 13);
for (const link of links) assert.equal(new URL(link.url).protocol, 'https:');
assert.ok(links.some((link) => link.url === 'https://web.evanchen.cc/geombook.html'));
assert.equal(readFileSync('public/CNAME', 'utf8').trim(), 'bw26.site');
console.log('BW26 launch checks passed: calendar boundaries, DST, exact-time countdown, event ordering, materials, and domain.');
